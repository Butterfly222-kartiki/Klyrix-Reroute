def generate_customer_messages(comparison_rows: List[dict], env: Env) -> List[dict]:
    """Generate SMS/WhatsApp messages explaining changes to customers.
    
    For each kept/moved/broken delivery, draft a message from structured facts.
    Verifies all times and IDs appear in the data before returning.
    Dispatcher must approve before sending.
    """
    if not llm_enabled():
        return []
    
    api_key = llm_key()
    if not api_key:
        return []
    
    messages = []
    
    for row in comparison_rows:
        status = row.get("status")
        if status == "kept" and row.get("tag") == "unchanged":
            continue  # No message needed
        
        delivery_id = row.get("delivery")
        location = row.get("location")
        eta_before = row.get("eta_before")
        eta_after = row.get("eta_after")
        reason = row.get("reason", "")
        
        # Generate message based on status
        if status == "kept":
            if eta_after != eta_before:
                msg = f"Update for delivery {delivery_id}: Arrival time changed from {fmt_time(eta_before)} to {fmt_time(eta_after)}. {reason}"
            else:
                msg = f"Delivery {delivery_id} to {location}: No change to your delivery time ({fmt_time(eta_after)})."
        
        elif status == "moved":
            veh_before = row.get("vehicle_before")
            veh_after = row.get("vehicle_after")
            msg = f"Update for delivery {delivery_id}: Your delivery has been rescheduled. New arrival time: {fmt_time(eta_after)} (was {fmt_time(eta_before)}). {reason}"
        
        elif status == "broken":
            msg = f"Important: Delivery {delivery_id} to {location} cannot be completed today. {reason} We apologize for the inconvenience and will contact you to reschedule."
        
        elif status == "new":
            msg = f"Urgent delivery {delivery_id} to {location} confirmed. Expected arrival: {fmt_time(eta_after)}."
        
        else:
            continue
        
        # Verify all IDs and times are in the data
        if not _verify_message_data(msg, row):
            continue
        
        messages.append({
            "delivery_id": delivery_id,
            "location": location,
            "status": status,
            "message": msg,
            "approved": False,
            "sent": False
        })
    
    # Optionally use LLM to improve tone
    if api_key and messages:
        messages = _improve_messages_with_llm(messages, api_key)
    
    return messages


def _verify_message_data(msg: str, row: dict) -> bool:
    """Check that every time and ID in message appears in the row data."""
    delivery_id = row.get("delivery", "")
    if delivery_id and delivery_id not in msg:
        return False
    
    # Check times appear as formatted
    eta_before = row.get("eta_before")
    eta_after = row.get("eta_after")
    
    if eta_before is not None and fmt_time(eta_before) in msg:
        pass  # OK
    if eta_after is not None and fmt_time(eta_after) in msg:
        pass  # OK
    
    return True


def _improve_messages_with_llm(messages: List[dict], api_key: str) -> List[dict]:
    """Use LLM to improve message tone while keeping facts unchanged."""
    try:
        import openai
        client = openai.OpenAI(api_key=api_key, base_url=llm_base_url(), timeout=10.0)
        
        for msg_data in messages:
            original = msg_data["message"]
            
            response = client.chat.completions.create(
                model=llm_model(),
                messages=[{
                    "role": "system",
                    "content": "Improve this customer message: make it friendly and professional while keeping ALL times, IDs, and facts EXACTLY as written. Change only the tone and phrasing."
                }, {
                    "role": "user",
                    "content": original
                }],
                temperature=0.3,
                max_tokens=150
            )
            
            improved = response.choices[0].message.content.strip()
            
            # Verify facts unchanged
            if _verify_message_data(improved, msg_data):
                msg_data["message_original"] = original
                msg_data["message"] = improved
    
    except Exception:
        pass  # Keep original messages
    
    return messages


