def check_window_violations(plan_state: dict, env: Any, threshold_minutes: float = 10) -> List[dict]:
    """Flag probable window violations before they happen.
    
    Returns list of alerts. Each alert triggers a proposed replan, not automatic.
    """
    alerts = []
    
    if not plan_state or "plan" not in plan_state:
        return alerts
    
    plan = plan_state["plan"]
    vehicles = plan.get("vehicles", {})
    now = plan.get("now", 0)
    
    for vid, veh in vehicles.items():
        rows = veh.get("rows", [])
        
        for row in rows:
            arrival = row.get("arrival")
            tw_end = row.get("tw_end")
            stop_id = row.get("stop_id")
            
            if arrival is None or tw_end is None:
                continue
            
            # Check if arrival is close to or past deadline
            lateness = arrival - tw_end
            
            if 0 < lateness <= threshold_minutes:
                alerts.append({
                    "type": "window_risk",
                    "vehicle": vid,
                    "stop": stop_id,
                    "location": row.get("location"),
                    "predicted_arrival": fmt_time(arrival),
                    "deadline": fmt_time(tw_end),
                    "lateness_minutes": round(lateness, 1),
                    "severity": "warning",
                    "action": "Consider replanning to meet deadline"
                })
            elif lateness > threshold_minutes:
                alerts.append({
                    "type": "window_violation",
                    "vehicle": vid,
                    "stop": stop_id,
                    "location": row.get("location"),
                    "predicted_arrival": fmt_time(arrival),
                    "deadline": fmt_time(tw_end),
                    "lateness_minutes": round(lateness, 1),
                    "severity": "critical",
                    "action": "Replan required to meet deadline"
                })
    
    return alerts


