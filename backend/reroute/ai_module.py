def _normalize_incident(inc: dict, now: float) -> dict:
    """Normalize LLM output to standard incident format."""
    inc_type = inc.get("type")
    if inc_type == "road_closure":
        closure = inc.get("road_closure", {})
        return {
            "type": "road_closure",
            "a": closure.get("a"),
            "b": closure.get("b"),
            "start": closure.get("start"),
            "end": closure.get("end"),
            "extra": closure.get("extra", 0),
            "factor": 1.0,
            "time": closure.get("start")
        }
    elif inc_type == "vehicle_breakdown":
        bd = inc.get("vehicle_breakdown", {})
        return {
            "type": "vehicle_breakdown",
            "vehicle_id": bd.get("vehicle_id"),
            "time": bd.get("time")
        }
    elif inc_type == "urgent_order":
        uo = inc.get("urgent_order", {})
        return {
            "type": "urgent_order",
            "time": uo.get("time"),
            "delivery": {
                "location": uo.get("location"),
                "weight": uo.get("weight", 5),
                "tw_start": uo.get("tw_start"),
                "tw_end": uo.get("tw_end"),
                "service": 5
            }
        }
    return inc


