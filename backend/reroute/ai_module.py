def llm_interpret_incident(text: str, env: Env, now: float, failed: Dict[str, dict], 
                          existing_ids: List[str]) -> Optional[dict]:
    """Interpret free-text incident reports using an LLM with structured output.
    
    Output goes through validate_incident. Unknown locations/vehicles are rejected.
    Handles multiple incidents, typos, mixed languages.
    
    Returns None if LLM unavailable, fails, or output is invalid.
    """
    if not llm_enabled():
        return None
    
    api_key = llm_key()
    if not api_key:
        return None
    
    try:
        # Try OpenAI first, fallback to Anthropic
        result = _call_openai(text, env, now, api_key) or _call_anthropic(text, env, now, api_key)
        if not result:
            return None
        
        # Validate all incidents in the response
        incidents = result if isinstance(result, list) else [result]
        validated = []
        
        for inc_data in incidents:
            try:
                inc = validate_incident(inc_data, env, now, failed, existing_ids)
                validated.append({
                    "type": inc.type,
                    "time": inc.time,
                    "data": inc.data,
                    "description": inc.description
                })
            except Exception:
                # Skip invalid incidents (unknown locations/vehicles rejected)
                continue
        
        if not validated:
            return None
        
        # Return single or multiple
        if len(validated) == 1:
            return {
                "ok": True,
                "incident": validated[0],
                "interpretation": "LLM interpretation",
                "assumptions": ["Generated by AI - please verify details"]
            }
        else:
            return {
                "ok": True,
                "incidents": validated,
                "interpretations": ["LLM interpretation"] * len(validated),
                "assumptions": ["Multiple incidents detected - each requires separate confirmation"]
            }
    
    except Exception as e:
        # Any error: return None so deterministic parser is used
        return None


def _call_openai(text: str, env: Env, now: float, api_key: str) -> Optional[Any]:
    """Call OpenAI API with function calling for structured output."""
    try:
        import openai
        client = openai.OpenAI(api_key=api_key, base_url=llm_base_url(), timeout=10.0)
    except ImportError:
        # Try urllib fallback
        return _call_openai_urllib(text, env, now, api_key)
    except Exception:
        return None
    
    try:
        locations = list(env.locations.keys())
        vehicles = list(env.vehicles.keys())
        
        tools = [{
            "type": "function",
            "function": {
                "name": "report_incident",
                "description": "Report one or more transportation incidents",
                "parameters": {
                    "type": "object",
                    "properties": {
                        "incidents": {
                            "type": "array",
                            "items": {
                                "type": "object",
                                "properties": {
                                    "type": {"type": "string", "enum": ["road_closure", "vehicle_breakdown", "urgent_order"]},
                                    "road_closure": {
                                        "type": "object",
                                        "properties": {
                                            "a": {"type": "string", "description": "Location A"},
                                            "b": {"type": "string", "description": "Location B"},
                                            "start": {"type": "string", "description": "Start time HH:MM"},
                                            "end": {"type": "string", "description": "End time HH:MM"},
                                            "extra": {"type": "number", "description": "Extra minutes"},
                                        }
                                    },
                                    "vehicle_breakdown": {
                                        "type": "object",
                                        "properties": {
                                            "vehicle_id": {"type": "string"},
                                            "time": {"type": "string", "description": "HH:MM"}
                                        }
                                    },
                                    "urgent_order": {
                                        "type": "object",
                                        "properties": {
                                            "location": {"type": "string"},
                                            "weight": {"type": "number"},
                                            "tw_start": {"type": "string"},
                                            "tw_end": {"type": "string"},
                                            "time": {"type": "string", "description": "Received at HH:MM"}
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }]
        
        response = client.chat.completions.create(
            model=llm_model(),
            messages=[{
                "role": "system",
                "content": f"Parse dispatcher reports into structured incidents. Available locations: {locations}. Available vehicles: {vehicles}. Current time: {fmt_time(now)}. Use ONLY exact IDs from the lists."
            }, {
                "role": "user",
                "content": text
            }],
            tools=tools,
            tool_choice={"type": "function", "function": {"name": "report_incident"}}
        )
        
        if response.choices[0].message.tool_calls:
            args = json.loads(response.choices[0].message.tool_calls[0].function.arguments)
            incidents = args.get("incidents", [])
            return [_normalize_incident(inc, now) for inc in incidents]
        
        return None
    
    except Exception:
        return None


def _call_openai_urllib(text: str, env: Env, now: float, api_key: str) -> Optional[Any]:
    """Fallback OpenAI call using stdlib urllib."""
    try:
        import urllib.request
        
        locations = list(env.locations.keys())
        vehicles = list(env.vehicles.keys())
        
        payload = {
            "model": llm_model(),
            "messages": [{
                "role": "system",
                "content": f"Parse this dispatcher report into JSON. Return ONLY valid JSON with incidents array. Available locations: {locations}. Vehicles: {vehicles}. Current time: {fmt_time(now)}."
            }, {
                "role": "user",
                "content": f"Report: {text}\n\nReturn JSON: {{\"incidents\": [{{\"type\": \"road_closure\", \"a\": \"LOC\", \"b\": \"LOC\", \"start\": \"HH:MM\", \"end\": \"HH:MM\", \"extra\": 0}}]}}"
            }],
            "temperature": 0.1
        }
        
        req = urllib.request.Request(
            llm_chat_url(),
            data=json.dumps(payload).encode("utf-8"),
            headers={
                "Authorization": f"Bearer {api_key}",
                "Content-Type": "application/json"
            }
        )
        
        with urllib.request.urlopen(req, timeout=10) as resp:
            data = json.loads(resp.read())
            content = data["choices"][0]["message"]["content"]
            # Extract JSON from markdown blocks if present
            match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", content, re.DOTALL)
            if match:
                content = match.group(1)
            result = json.loads(content)
            incidents = result.get("incidents", [])
            return [_normalize_incident(inc, now) for inc in incidents]
    
    except Exception:
        return None


