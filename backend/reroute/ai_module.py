def answer_why_question(question: str, plan_state: dict, comparison: dict, 
                       events: List[dict]) -> dict:
    """Answer dispatcher questions using only plan data, comparison, and audit log.
    
    Read-only access. No hallucination - only cite facts from the provided data.
    """
    if not llm_enabled():
        return {"answer": "LLM not available", "sources": []}
    
    api_key = llm_key()
    if not api_key:
        return {"answer": "LLM API key not set", "sources": []}
    
    try:
        import openai
        client = openai.OpenAI(api_key=api_key, timeout=15.0)
        
        # Build context from data
        context = _build_context(plan_state, comparison, events)
        
        response = client.chat.completions.create(
            model=llm_model(),
            messages=[{
                "role": "system",
                "content": "You are a dispatcher assistant. Answer questions using ONLY the provided data. Cite specific facts. If the answer isn't in the data, say 'I cannot determine that from the current data.'"
            }, {
                "role": "user",
                "content": f"Context:\n{context}\n\nQuestion: {question}"
            }],
            temperature=0.1,
            max_tokens=300
        )
        
        answer = response.choices[0].message.content.strip()
        
        # Extract cited facts as sources
        sources = _extract_sources(answer, comparison, events)
        
        return {"answer": answer, "sources": sources, "grounded": True}
    
    except Exception as e:
        return {"answer": f"Error: {e}", "sources": [], "grounded": False}


def _build_context(plan_state: dict, comparison: dict, events: List[dict]) -> str:
    """Build context string from plan data."""
    lines = []
    
    # Plan summary
    if plan_state and "plan" in plan_state:
        plan = plan_state["plan"]
        metrics = plan.get("metrics", {})
        lines.append(f"Current plan: {metrics.get('deliveries', 0)} deliveries, {metrics.get('completed', 0)} completed, {metrics.get('unfulfilled', 0)} unfulfilled.")
    
    # Comparison
    if comparison and "rows" in comparison:
        rows = comparison["rows"]
        summary = comparison.get("summary", {})
        lines.append(f"Last change: kept {summary.get('kept', 0)}, moved {summary.get('moved', 0)}, broken {summary.get('broken', 0)}.")
        
        # List moved/broken deliveries
        moved = [r for r in rows if r.get("status") == "moved"]
        broken = [r for r in rows if r.get("status") == "broken"]
        
        if moved:
            lines.append(f"Moved deliveries: {', '.join(r.get('delivery', '') for r in moved[:5])}")
        if broken:
            lines.append(f"Broken deliveries: {', '.join(r.get('delivery', '') for r in broken[:5])}")
    
    # Events
    if events:
        lines.append(f"Recent incidents ({len(events)}):")
        for evt in events[-3:]:
            inc = evt.get("incident", {})
            lines.append(f"  - {inc.get('description', 'N/A')} at {fmt_time(evt.get('time', 0))}")
    
    return "\n".join(lines)


def _extract_sources(answer: str, comparison: dict, events: List[dict]) -> List[str]:
    """Extract which data sources were referenced in the answer."""
    sources = []
    
    # Check for delivery IDs
    if comparison and "rows" in comparison:
        for row in comparison["rows"]:
            did = row.get("delivery", "")
            if did and did in answer:
                sources.append(f"Comparison row for {did}")
    
    # Check for incidents
    if events:
        for evt in events:
            desc = evt.get("incident", {}).get("description", "")
            if any(word in answer.lower() for word in desc.lower().split()[:3]):
                sources.append(f"Incident: {desc}")
    
    return list(set(sources))


